// Keep request-schema restrictions out of the shared form schema: other API
// consumers still use field names as relationship aliases.
type requestSchemaResource struct {
	RequestSchemaResource
}

var _ resource.ResourceWithModifyPlan = (*requestSchemaResource)(nil)

func (r *requestSchemaResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	r.RequestSchemaResource.Schema(ctx, req, resp)
	fields, ok := resp.Schema.Attributes["fields"].(schema.ListNestedAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected fields to be a list of nested objects.")
		return
	}
	for _, member := range requestSchemaFieldTypes {
		if _, ok := fields.NestedObject.Attributes[member].(schema.SingleNestedAttribute); !ok {
			resp.Diagnostics.AddError("Unexpected request-schema schema", fmt.Sprintf("Expected %s to be a nested field type.", member))
			return
		}
	}
	name, ok := fields.NestedObject.Attributes["name"].(schema.StringAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected the nested field name to be a string.")
		return
	}
	name.Optional = false
	name.Computed = true
	name.PlanModifiers = nil
	name.Description = "Server-generated field name. Remove nested name assignments from configuration; keep the top-level request schema name."
	fields.NestedObject.Attributes["name"] = name

	stringField, ok := fields.NestedObject.Attributes["string_field"].(schema.SingleNestedAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected string_field to be a nested object.")
		return
	}
	for _, member := range requestSchemaStringViews {
		if _, ok := stringField.Attributes[member].(schema.SingleNestedAttribute); !ok {
			resp.Diagnostics.AddError("Unexpected request-schema schema", fmt.Sprintf("Expected %s to be a nested string view.", member))
			return
		}
	}
	stringField.Validators = append(stringField.Validators, requestSchemaStringView{})
	fields.NestedObject.Attributes["string_field"] = stringField
	fields.NestedObject.Validators = append(fields.NestedObject.Validators, requestSchemaFieldType{})
	resp.Schema.Attributes["fields"] = fields
}

// Terraform may highlight the top-level "name" for a nested computed-attribute
// error. Give migration guidance with the exact nested path as well.
func (r *requestSchemaResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var fields types.List
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("fields"), &fields)...)
	if resp.Diagnostics.HasError() || fields.IsNull() || fields.IsUnknown() {
		return
	}
	for index, value := range fields.Elements() {
		field, ok := value.(types.Object)
		if !ok {
			resp.Diagnostics.AddAttributeError(path.Root("fields").AtListIndex(index), "Invalid request-schema field", "Expected a nested field object.")
			return
		}
		if field.IsNull() || field.IsUnknown() || field.Attributes()["name"].IsNull() {
			continue
		}
		resp.Diagnostics.AddAttributeError(
			path.Root("fields").AtListIndex(index).AtName("name"),
			"Nested request-schema field name is read-only",
			fmt.Sprintf("Remove fields[%d].name from configuration; it is generated by the server. Keep the top-level resource name. Existing state and imports do not require replacement.", index),
		)
	}
}

var requestSchemaFieldTypes = [...]string{"string_field", "bool_field", "int64_field", "file_field", "oauth2_field", "string_map_field"}

type requestSchemaFieldType struct{}

func (requestSchemaFieldType) Description(context.Context) string {
	return "Configure exactly one field type: string_field, bool_field, int64_field, file_field, oauth2_field, or string_map_field."
}

func (v requestSchemaFieldType) MarkdownDescription(ctx context.Context) string {
	return v.Description(ctx)
}

func (v requestSchemaFieldType) ValidateObject(ctx context.Context, req validator.ObjectRequest, resp *validator.ObjectResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	if !requestSchemaValidOneOf(req.ConfigValue, requestSchemaFieldTypes[:]) {
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid request-schema field type", fmt.Sprintf("%s: %s", req.Path.String(), v.Description(ctx)))
	}
}

func requestSchemaValidOneOf(value types.Object, members []string) bool {
	configured, unresolved := 0, false
	attributes := value.Attributes()
	for _, name := range members {
		member := attributes[name]
		if member.IsUnknown() {
			unresolved = true
		} else if !member.IsNull() {
			configured++
		}
	}
	// Unknown expressions can resolve to null, but cannot fix a known conflict.
	return configured <= 1 && (configured == 1 || unresolved)
}

var requestSchemaStringViews = [...]string{"text_field", "password_field", "select_field", "picker_field", "date_field"}

type requestSchemaStringView struct{}

func (requestSchemaStringView) Description(context.Context) string {
	return "Configure exactly one string view: text_field, password_field, select_field, picker_field, or date_field."
}

func (v requestSchemaStringView) MarkdownDescription(ctx context.Context) string {
	return v.Description(ctx)
}

func (v requestSchemaStringView) ValidateObject(ctx context.Context, req validator.ObjectRequest, resp *validator.ObjectResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	if !requestSchemaValidOneOf(req.ConfigValue, requestSchemaStringViews[:]) {
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid request-schema string view", fmt.Sprintf("%s: %s", req.Path.String(), v.Description(ctx)))
	}
}

// Check the converted payload as well as configuration: values deferred during
// planning must not become a malformed write when resolved or omitted.
func validateRequestSchemaWriteFields(ctx context.Context, fields []shared.FormField) diag.Diagnostics {
	var diagnostics diag.Diagnostics
	for index, field := range fields {
		fieldPath := path.Root("fields").AtListIndex(index)
		if requestSchemaCountPresent(
			field.StringField != nil, field.BoolField != nil, field.Int64Field != nil,
			field.FileField != nil, field.Oauth2Field != nil, field.StringMapField != nil,
		) != 1 {
			diagnostics.AddAttributeError(fieldPath, "Invalid request-schema field type", fmt.Sprintf("%s: %s", fieldPath.String(), (requestSchemaFieldType{}).Description(ctx)))
			continue
		}
		if view := field.StringField; view != nil && requestSchemaCountPresent(
			view.TextField != nil, view.PasswordField != nil, view.SelectField != nil,
			view.PickerField != nil, view.DateField != nil,
		) != 1 {
			viewPath := fieldPath.AtName("string_field")
			diagnostics.AddAttributeError(viewPath, "Invalid request-schema string view", fmt.Sprintf("%s: %s", viewPath.String(), (requestSchemaStringView{}).Description(ctx)))
		}
	}
	return diagnostics
}

func requestSchemaCountPresent(values ...bool) int {
	var count int
	for _, present := range values {
		if present {
			count++
		}
	}
	return count
}

// A generated name also depends on preceding labels (duplicate suffixes).
// Compare the sequence once per resource, not once for every field name.
func (r *requestSchemaResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.Plan.Raw.IsNull() || req.State.Raw.IsNull() {
		return
	}
	var configured, stored types.List
	fieldsPath := path.Root("fields")
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, fieldsPath, &configured)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, fieldsPath, &stored)...)
	if resp.Diagnostics.HasError() || configured.IsNull() || configured.IsUnknown() || stored.IsNull() || stored.IsUnknown() {
		return
	}
	configFields, stateFields := configured.Elements(), stored.Elements()
	if len(configFields) != len(stateFields) {
		return
	}
	storedNames := make([]attr.Value, len(stateFields))
	for index, value := range configFields {
		configField, ok := value.(types.Object)
		if !ok {
			return
		}
		stateField, ok := stateFields[index].(types.Object)
		if !ok {
			return
		}
		if configField.IsNull() || configField.IsUnknown() || stateField.IsNull() || stateField.IsUnknown() {
			return
		}
		configLabel := configField.Attributes()["display_name"]
		stateAttributes := stateField.Attributes()
		stateLabel := stateAttributes["display_name"]
		if configLabel.IsNull() || configLabel.IsUnknown() || !configLabel.Equal(stateLabel) {
			return
		}
		storedNames[index] = stateAttributes["name"]
	}
	var planned types.List
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, fieldsPath, &planned)...)
	if resp.Diagnostics.HasError() || planned.IsNull() || planned.IsUnknown() {
		return
	}
	planFields := planned.Elements()
	if len(planFields) != len(stateFields) {
		return
	}
	changed := false
	for index, value := range planFields {
		field, ok := value.(types.Object)
		if !ok || field.IsNull() || field.IsUnknown() {
			return
		}
		attributes := field.Attributes()
		storedName := storedNames[index]
		if !attributes["name"].IsUnknown() || storedName.IsNull() || storedName.IsUnknown() {
			continue
		}
		attributes["name"] = storedName
		updated, diagnostics := types.ObjectValue(field.AttributeTypes(ctx), attributes)
		resp.Diagnostics.Append(diagnostics...)
		if resp.Diagnostics.HasError() {
			return
		}
		planFields[index] = updated
		changed = true
	}
	if changed {
		updated, diagnostics := types.ListValue(planned.ElementType(ctx), planFields)
		resp.Diagnostics.Append(diagnostics...)
		if !resp.Diagnostics.HasError() {
			resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, fieldsPath, updated)...)
		}
	}
}

// Generated refreshPlan reapplies the plan after decoding the API response and
// clears unknown nested names. Restore only this resource's output-only names,
// leaving configured attributes and shared form conversion semantics untouched.
func restoreRequestSchemaFieldNames(data *RequestSchemaResourceModel, form *shared.RequestSchemaForm) {
	if data == nil || form == nil {
		return
	}
	for index := range data.Fields {
		if index < len(form.Fields) {
			data.Fields[index].Name = types.StringPointerValue(form.Fields[index].Name)
		}
	}
}
