// Keep request-schema restrictions out of the shared form schema: other API
// consumers still use field names as relationship aliases.
type requestSchemaResource struct {
	RequestSchemaResource
}

func (r *requestSchemaResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	r.RequestSchemaResource.Schema(ctx, req, resp)
	fields, ok := resp.Schema.Attributes["fields"].(schema.ListNestedAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected fields to be a list of nested objects.")
		return
	}
	name, ok := fields.NestedObject.Attributes["name"].(schema.StringAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected the nested field name to be a string.")
		return
	}
	name.Optional = false
	name.Computed = true
	name.PlanModifiers = []planmodifier.String{requestSchemaFieldName{}}
	name.Description = "Server-generated field name. Remove nested name assignments from configuration; keep the top-level request schema name."
	fields.NestedObject.Attributes["name"] = name

	stringField, ok := fields.NestedObject.Attributes["string_field"].(schema.SingleNestedAttribute)
	if !ok {
		resp.Diagnostics.AddError("Unexpected request-schema schema", "Expected string_field to be a nested object.")
		return
	}
	stringField.Validators = append(stringField.Validators, requestSchemaStringView{})
	fields.NestedObject.Attributes["string_field"] = stringField
	resp.Schema.Attributes["fields"] = fields
}

// Terraform may highlight the top-level "name" for a nested computed-attribute
// error. Give migration guidance with the exact nested path as well.
func (r *requestSchemaResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var fields types.List
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("fields"), &fields)...)
	if resp.Diagnostics.HasError() || fields.IsNull() || fields.IsUnknown() {
		return
	}
	for index, value := range fields.Elements() {
		field, ok := value.(types.Object)
		if !ok {
			resp.Diagnostics.AddAttributeError(path.Root("fields").AtListIndex(index), "Invalid request-schema field", "Expected a nested field object.")
			return
		}
		if field.IsNull() || field.IsUnknown() || field.Attributes()["name"].IsNull() {
			continue
		}
		resp.Diagnostics.AddAttributeError(
			path.Root("fields").AtListIndex(index).AtName("name"),
			"Nested request-schema field name is read-only",
			fmt.Sprintf("Remove fields[%d].name from configuration; it is generated by the server. Keep the top-level resource name. Existing state and imports do not require replacement.", index),
		)
	}
}

var requestSchemaStringViews = [...]string{"text_field", "password_field", "select_field", "picker_field", "date_field"}

type requestSchemaStringView struct{}

func (requestSchemaStringView) Description(context.Context) string {
	return "Configure exactly one string view: text_field, password_field, select_field, picker_field, or date_field."
}

func (v requestSchemaStringView) MarkdownDescription(ctx context.Context) string {
	return v.Description(ctx)
}

func (v requestSchemaStringView) ValidateObject(ctx context.Context, req validator.ObjectRequest, resp *validator.ObjectResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	configured, unresolved := 0, false
	attributes := req.ConfigValue.Attributes()
	for _, name := range requestSchemaStringViews {
		value := attributes[name]
		if value.IsUnknown() {
			unresolved = true
		} else if !value.IsNull() {
			configured++
		}
	}
	// A known conflict cannot be resolved by unknown values. Otherwise defer
	// until unknown expressions resolve, including expressions resolving to null.
	if configured > 1 || (configured == 0 && !unresolved) {
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid request-schema string view", fmt.Sprintf("%s: %s", req.Path.String(), v.Description(ctx)))
	}
}

// A generated name also depends on the preceding labels (duplicate suffixes).
// Only reuse names when the complete label sequence is known and unchanged.
type requestSchemaFieldName struct{}

func (requestSchemaFieldName) Description(context.Context) string {
	return "The server-generated field name will not change while the field labels are unchanged."
}

func (m requestSchemaFieldName) MarkdownDescription(ctx context.Context) string {
	return m.Description(ctx)
}

func (requestSchemaFieldName) PlanModifyString(ctx context.Context, req planmodifier.StringRequest, resp *planmodifier.StringResponse) {
	if !req.PlanValue.IsUnknown() || req.StateValue.IsNull() || req.StateValue.IsUnknown() {
		return
	}
	var configured, stored types.List
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, req.Path.ParentPath().ParentPath(), &configured)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, req.Path.ParentPath().ParentPath(), &stored)...)
	if resp.Diagnostics.HasError() || configured.IsNull() || configured.IsUnknown() || stored.IsNull() || stored.IsUnknown() {
		return
	}
	configFields, stateFields := configured.Elements(), stored.Elements()
	if len(configFields) != len(stateFields) {
		return
	}
	for index, value := range configFields {
		configField, ok := value.(types.Object)
		if !ok {
			return
		}
		stateField, ok := stateFields[index].(types.Object)
		if !ok {
			return
		}
		if configField.IsNull() || configField.IsUnknown() || stateField.IsNull() || stateField.IsUnknown() {
			return
		}
		configLabel := configField.Attributes()["display_name"]
		stateLabel := stateField.Attributes()["display_name"]
		if configLabel.IsNull() || configLabel.IsUnknown() || !configLabel.Equal(stateLabel) {
			return
		}
	}
	resp.PlanValue = req.StateValue
}

// Generated refreshPlan reapplies the plan after decoding the API response and
// clears unknown nested names. Restore only this resource's output-only names,
// leaving configured attributes and shared form conversion semantics untouched.
func restoreRequestSchemaFieldNames(data *RequestSchemaResourceModel, form *shared.RequestSchemaForm) {
	if data == nil || form == nil {
		return
	}
	for index := range data.Fields {
		if index < len(form.Fields) {
			data.Fields[index].Name = types.StringPointerValue(form.Fields[index].Name)
		}
	}
}
